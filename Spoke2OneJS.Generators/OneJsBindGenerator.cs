using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Spoke2OneJS.Generators
{
    /// <summary>
    /// For every field marked with [OneJsBind("Name")]:
    /// <list type="bullet">
    /// <item>whose type exposes a <c>Now</c> property (Spoke State&lt;T&gt;, Signal&lt;T&gt;, ...), generates
    /// <c>public T Name => _field.Now;</c> plus an <c>OnNameChanged</c> event forwarding to Subscribe/Unsubscribe,
    /// which is the shape OneJS's useEventSync expects; with <c>OneJsBindMode.TwoWay</c> the property also gets
    /// a setter calling <c>_field.Set(value)</c>;</item>
    /// <item>whose type has an <c>Invoke</c> method (Spoke Trigger, Trigger&lt;T&gt;), generates
    /// <c>public void Name(...) => _field.Invoke(...);</c> so JS can fire the trigger.</item>
    /// </list>
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class OneJsBindGenerator : IIncrementalGenerator
    {
        const string AttributeNamespace = "Spoke2OneJS";
        const string AttributeName = "OneJsBindAttribute";
        const string AttributeFullName = AttributeNamespace + "." + AttributeName;

        const string AttributeSource = @"// <auto-generated/>
namespace Spoke2OneJS
{
    /// <summary>
    /// Exposes a Spoke field to OneJS. For a signal/state it generates a <c>Name</c> property returning the
    /// current value and an <c>OnNameChanged</c> event forwarding to Subscribe/Unsubscribe; for a trigger it
    /// generates a <c>Name(...)</c> method that invokes it. The containing type must be partial. When no name is given it is derived from the field name
    /// (<c>_history</c> / <c>m_history</c> -> <c>History</c>).
    /// </summary>
    [global::System.AttributeUsage(global::System.AttributeTargets.Field, AllowMultiple = false, Inherited = false)]
    [global::System.Diagnostics.Conditional(""SPOKE2ONEJS_KEEP_ATTRIBUTES"")]
    internal sealed class OneJsBindAttribute : global::System.Attribute
    {
        public OneJsBindAttribute() { }
        public OneJsBindAttribute(string name) { Name = name; }
        public OneJsBindAttribute(OneJsBindMode mode) { Mode = mode; }
        public OneJsBindAttribute(string name, OneJsBindMode mode) { Name = name; Mode = mode; }
        public string Name { get; }
        public OneJsBindMode Mode { get; }
    }

    /// <summary>How a state field is exposed to OneJS.</summary>
    internal enum OneJsBindMode
    {
        /// <summary>Read-only property: JS reads the value and listens for changes.</summary>
        OneWay,
        /// <summary>Read-write property: the setter writes back to the state via <c>Set(value)</c>.</summary>
        TwoWay,
    }
}
";

        static readonly DiagnosticDescriptor NotPartial = new(
            "OJS001", "Containing type must be partial",
            "Type '{0}' must be declared partial to use [OneJsBind]",
            "Spoke2OneJS", DiagnosticSeverity.Error, isEnabledByDefault: true);

        static readonly DiagnosticDescriptor NoNowProperty = new(
            "OJS002", "Field type is not bindable",
            "Field '{0}' of type '{1}' cannot be bound: the type has neither a readable 'Now' property nor an 'Invoke' method",
            "Spoke2OneJS", DiagnosticSeverity.Error, isEnabledByDefault: true);

        static readonly DiagnosticDescriptor InvalidName = new(
            "OJS003", "Invalid bind name",
            "'{0}' is not a valid C# identifier for a [OneJsBind] property",
            "Spoke2OneJS", DiagnosticSeverity.Error, isEnabledByDefault: true);

        static readonly DiagnosticDescriptor TwoWayOnTrigger = new(
            "OJS004", "Two-way binding on a trigger",
            "Field '{0}' is a trigger and cannot use OneJsBindMode.TwoWay; two-way binding applies to state fields only",
            "Spoke2OneJS", DiagnosticSeverity.Error, isEnabledByDefault: true);

        static readonly DiagnosticDescriptor NoSetMethod = new(
            "OJS005", "Field type is not writable",
            "Field '{0}' of type '{1}' cannot use OneJsBindMode.TwoWay: the type has no 'Set({2})' method",
            "Spoke2OneJS", DiagnosticSeverity.Error, isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(ctx =>
                ctx.AddSource(AttributeName + ".g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

            var results = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeFullName,
                predicate: static (node, _) => node is VariableDeclaratorSyntax,
                transform: static (ctx, _) => Analyze(ctx));

            context.RegisterSourceOutput(results, static (spc, result) =>
            {
                if (result.Diagnostic is { } diagnostic)
                    spc.ReportDiagnostic(diagnostic.ToDiagnostic());
                else if (result.Binding is { } binding)
                    spc.AddSource(binding.HintName, SourceText.From(Render(binding), Encoding.UTF8));
            });
        }

        static Result Analyze(GeneratorAttributeSyntaxContext ctx)
        {
            var field = (IFieldSymbol)ctx.TargetSymbol;
            var location = ctx.TargetNode.GetLocation();

            for (var type = field.ContainingType; type != null; type = type.ContainingType)
            {
                if (!IsPartial(type))
                    return Result.Error(NotPartial, location, type.Name);
            }

            var nowType = FindNowProperty(field.Type)?.Type;
            var invoke = nowType == null ? FindInvokeMethod(field.Type) : null;
            if (nowType == null && invoke == null)
                return Result.Error(NoNowProperty, location, field.Name, field.Type.ToDisplayString());

            string? name = null;
            var twoWay = false;
            foreach (var arg in ctx.Attributes[0].ConstructorArguments)
            {
                if (arg.Value is string s)
                    name = s;
                else if (arg.Kind == TypedConstantKind.Enum)
                    twoWay = arg.Value is int mode && mode == 1; // OneJsBindMode.TwoWay
            }

            if (twoWay && nowType == null)
                return Result.Error(TwoWayOnTrigger, location, field.Name);
            if (twoWay && !HasSetMethod(field.Type, nowType!))
                return Result.Error(NoSetMethod, location, field.Name, field.Type.ToDisplayString(), nowType!.ToDisplayString());

            if (string.IsNullOrEmpty(name))
                name = DeriveName(field.Name);
            if (!SyntaxFacts.IsValidIdentifier(name!) || SyntaxFacts.GetKeywordKind(name!) != SyntaxKind.None)
                return Result.Error(InvalidName, location, name ?? "");

            var ns = field.ContainingType!.ContainingNamespace;
            var containingTypes = new List<string>();
            for (var type = field.ContainingType; type != null; type = type.ContainingType)
                containingTypes.Insert(0, TypeDeclaration(type));

            var typeId = field.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                .Replace("global::", "").Replace('<', '[').Replace('>', ']');

            return new Result(new Binding(
                HintName: $"{typeId}.{field.Name}.OneJsBind.g.cs",
                Namespace: ns.IsGlobalNamespace ? null : ns.ToDisplayString(),
                ContainingTypes: string.Join("\n", containingTypes),
                ContainingTypeCount: containingTypes.Count,
                FieldName: field.Name,
                Kind: nowType != null ? BindingKind.State : BindingKind.Trigger,
                ValueType: nowType?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                InvokeParameters: invoke == null ? "" : string.Join(", ", invoke.Parameters.Select(p =>
                    p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + " " + EscapeIdentifier(p.Name))),
                InvokeArguments: invoke == null ? "" : string.Join(", ", invoke.Parameters.Select(p => EscapeIdentifier(p.Name))),
                Name: name!,
                TwoWay: twoWay,
                IsStatic: field.IsStatic), null);
        }

        static bool IsPartial(INamedTypeSymbol type) =>
            type.DeclaringSyntaxReferences.Any(r =>
                r.GetSyntax() is TypeDeclarationSyntax decl &&
                decl.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)));

        static IPropertySymbol? FindNowProperty(ITypeSymbol type)
        {
            IEnumerable<ITypeSymbol> candidates = new[] { type };
            for (var b = type.BaseType; b != null; b = b.BaseType)
                candidates = candidates.Append(b);
            candidates = candidates.Concat(type.AllInterfaces);

            return candidates
                .SelectMany(t => t.GetMembers("Now"))
                .OfType<IPropertySymbol>()
                .FirstOrDefault(p => !p.IsStatic && p.GetMethod != null && p.Parameters.IsEmpty);
        }

        static bool HasSetMethod(ITypeSymbol type, ITypeSymbol valueType)
        {
            IEnumerable<ITypeSymbol> candidates = new[] { type };
            for (var b = type.BaseType; b != null; b = b.BaseType)
                candidates = candidates.Append(b);
            candidates = candidates.Concat(type.AllInterfaces);

            return candidates
                .SelectMany(t => t.GetMembers("Set"))
                .OfType<IMethodSymbol>()
                .Any(m => !m.IsStatic && m.Parameters.Length == 1 &&
                          SymbolEqualityComparer.Default.Equals(m.Parameters[0].Type, valueType));
        }

        static IMethodSymbol? FindInvokeMethod(ITypeSymbol type)
        {
            for (var t = type; t != null; t = t.BaseType)
            {
                var invoke = t.GetMembers("Invoke").OfType<IMethodSymbol>()
                    .Where(m => !m.IsStatic && m.DeclaredAccessibility == Accessibility.Public && m.TypeParameters.IsEmpty)
                    // Trigger<T> has both Invoke() and Invoke(T); prefer the payload overload.
                    .OrderByDescending(m => m.Parameters.Length)
                    .FirstOrDefault();
                if (invoke != null)
                    return invoke;
            }
            return null;
        }

        static string EscapeIdentifier(string name) =>
            SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

        static string DeriveName(string fieldName)
        {
            var trimmed = fieldName.StartsWith("m_") ? fieldName.Substring(2) : fieldName.TrimStart('_');
            return trimmed.Length == 0 ? fieldName : char.ToUpperInvariant(trimmed[0]) + trimmed.Substring(1);
        }

        static string TypeDeclaration(INamedTypeSymbol type)
        {
            var keyword = (type.IsRecord, type.TypeKind) switch
            {
                (true, TypeKind.Struct) => "record struct",
                (true, _) => "record",
                (_, TypeKind.Struct) => "struct",
                (_, TypeKind.Interface) => "interface",
                _ => "class",
            };
            var typeParams = type.TypeParameters.IsEmpty
                ? ""
                : "<" + string.Join(", ", type.TypeParameters.Select(p => p.Name)) + ">";
            return $"partial {keyword} {type.Name}{typeParams}";
        }

        static string Render(Binding b)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable disable");
            sb.AppendLine();

            var indent = "";
            if (b.Namespace != null)
            {
                sb.AppendLine($"namespace {b.Namespace}");
                sb.AppendLine("{");
                indent += "    ";
            }

            foreach (var decl in b.ContainingTypes.Split('\n'))
            {
                sb.AppendLine(indent + decl);
                sb.AppendLine(indent + "{");
                indent += "    ";
            }

            var mod = b.IsStatic ? "public static" : "public";
            if (b.Kind == BindingKind.Trigger)
                RenderTrigger(sb, b, indent, mod);
            else
                RenderState(sb, b, indent, mod);

            var closers = b.ContainingTypeCount + (b.Namespace != null ? 1 : 0);
            for (var i = 0; i < closers; i++)
            {
                indent = indent.Substring(4);
                sb.AppendLine(indent + "}");
            }

            return sb.ToString();
        }

        static void RenderTrigger(StringBuilder sb, Binding b, string indent, string mod)
        {
            sb.AppendLine($"{indent}{mod} void {b.Name}({b.InvokeParameters})");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{indent}    {b.FieldName}.Invoke({b.InvokeArguments});");
            sb.AppendLine($"{indent}}}");
        }

        static void RenderState(StringBuilder sb, Binding b, string indent, string mod)
        {
            if (b.TwoWay)
            {
                sb.AppendLine($"{indent}{mod} {b.ValueType} {b.Name}");
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    get => {b.FieldName}.Now;");
                sb.AppendLine($"{indent}    set => {b.FieldName}.Set(value);");
                sb.AppendLine($"{indent}}}");
            }
            else
            {
                sb.AppendLine($"{indent}{mod} {b.ValueType} {b.Name} => {b.FieldName}.Now;");
            }
            sb.AppendLine();
            sb.AppendLine($"{indent}{mod} event global::System.Action On{b.Name}Changed");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{indent}    add");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        {b.FieldName}.Subscribe(value);");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    remove");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        {b.FieldName}.Unsubscribe(value);");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}}}");
        }

        // Value-equatable models so the incremental pipeline can cache between edits.

        enum BindingKind { State, Trigger }

        sealed record Binding(
            string HintName,
            string? Namespace,
            string ContainingTypes,
            int ContainingTypeCount,
            string FieldName,
            BindingKind Kind,
            string? ValueType,
            string InvokeParameters,
            string InvokeArguments,
            string Name,
            bool TwoWay,
            bool IsStatic);

        sealed record DiagnosticInfo(DiagnosticDescriptor Descriptor, LocationInfo? Location, EquatableArray Args)
        {
            public Diagnostic ToDiagnostic() =>
                Diagnostic.Create(Descriptor, Location?.ToLocation(), Args.Items.ToArray<object>());
        }

        sealed record LocationInfo(string FilePath, TextSpan Span, LinePositionSpan LineSpan)
        {
            public Location ToLocation() => Location.Create(FilePath, Span, LineSpan);

            public static LocationInfo? From(Location location) =>
                location.SourceTree == null
                    ? null
                    : new LocationInfo(location.SourceTree.FilePath, location.SourceSpan, location.GetLineSpan().Span);
        }

        sealed record Result(Binding? Binding, DiagnosticInfo? Diagnostic)
        {
            public static Result Error(DiagnosticDescriptor descriptor, Location location, params string[] args) =>
                new(null, new DiagnosticInfo(descriptor, LocationInfo.From(location), new EquatableArray(args.ToImmutableArray())));
        }

        readonly struct EquatableArray : System.IEquatable<EquatableArray>
        {
            public EquatableArray(ImmutableArray<string> items) => Items = items;
            public ImmutableArray<string> Items { get; }
            public bool Equals(EquatableArray other) => Items.SequenceEqual(other.Items);
            public override bool Equals(object? obj) => obj is EquatableArray other && Equals(other);
            public override int GetHashCode() => Items.Aggregate(17, (h, s) => h * 31 + (s?.GetHashCode() ?? 0));
        }
    }
}
